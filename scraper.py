'''
Web-скрапінг стрічки новин сайту ukrinform.ua з підтримкою пагінації сторінок.
Синтез фейкових новин для тестування класифікатора.
'''

import requests
from bs4 import BeautifulSoup

# URL стрічки новин ukrinform.ua
BASE_URL = 'https://www.ukrinform.ua/block-lastnews'
# Шаблон URL для пагінації
PAGE_URL = 'https://www.ukrinform.ua/block-lastnews?page={}'

# Заголовок запиту
HEADERS = {
    'User-Agent': (
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) '
        'AppleWebKit/537.36 (KHTML, like Gecko) '
        'Chrome/143.0.0.0 Safari/537.36'
    )
}


def scrape_page(url):
    '''
    Отримує список новин з однієї сторінки URL.
    '''
    try:
        response = requests.get(url, headers=HEADERS, timeout=10)
        response.raise_for_status()
    except requests.RequestException as e:
        print(f'  {url}: {e}')
        return []

    soup = BeautifulSoup(response.text, 'lxml')

    # Кожна новина
    articles = soup.find_all('article')
    texts = []
    for article in articles:
        section = article.find('section')
        if not section:
            continue
        # Заголовок
        h2 = section.find('h2')
        title = ''
        if h2:
            a_tag = h2.find('a')
            if a_tag and a_tag.text.strip():
                title = a_tag.text.strip()
        # Опис
        desc = ''
        for p in section.find_all('p'):
            if p.text.strip():
                desc = p.text.strip()
                break
        # Обєднуємо заголовок та опис
        if title:
            full_text = f'{title}. {desc}' if desc else title
            texts.append(full_text)
    return texts


def scrape_news(pages=7):
    '''
    Отримує новини з кількох сторінок ukrinform.ua/block-lastnews.
    '''
    print(f'Джерело: {BASE_URL}')
    all_news = []

    # Перша сторінка
    print(f'  Сторінка 1: {BASE_URL}')
    page_news = scrape_page(BASE_URL)
    all_news.extend(page_news)
    print(f'  Отримано: {len(page_news)} новин')

    # Наступні сторінки через пагінацію
    for page_num in range(2, pages + 1):
        url = PAGE_URL.format(page_num)
        print(f'  Сторінка {page_num}: {url}')
        page_news = scrape_page(url)
        all_news.extend(page_news)
        print(f'  Отримано: {len(page_news)} новин')

    # Видаляємо дублікати зберігаючи порядок
    seen = set()
    unique_news = []
    for text in all_news:
        if text not in seen:
            seen.add(text)
            unique_news.append(text)

    print(f'Всього отримано: {len(unique_news)} унікальних новин')
    return unique_news


